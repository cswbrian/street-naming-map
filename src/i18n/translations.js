const ROAD_TYPE_KEYS = {
  Highway: 'roadTypeHighway',
  'Main Road': 'roadTypeMainRoad',
  'Secondary Road': 'roadTypeSecondaryRoad',
  'Restricted Road': 'roadTypeRestrictedRoad',
  Tunnel: 'roadTypeTunnel',
  Track: 'roadTypeTrack',
  'Unknown Type': 'roadTypeUnknown',
}

export function getRoadTypeLabel(locale, streetType) {
  const key = ROAD_TYPE_KEYS[streetType] ?? 'roadTypeUnknown'
  return translations[locale]?.[key] ?? streetType ?? translations[locale].roadTypeUnknown
}

